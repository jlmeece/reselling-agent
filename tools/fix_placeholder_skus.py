"""
One-off: replace placeholder SKUs in col AA (e.g. "X4fb2cfc373" — generated by backfill_skus
before it could parse the /p/-/slug/<id> URL shape) with the real Costco product id from col R,
and keep the branded photos mapped to the new SKU. Then run tools/sync_ebay_skus.py so eBay's
SKU matches the sheet.

Placeholder = a non-blank col AA that isn't a pure digit string (real Costco ids are digits).
A col AA that already holds digits is NEVER rewritten; a blank one is left to backfill_skus.

Per fixed row:
  - col AA = the real id (the ONLY sheet column written; row re-read right before the write and
    skipped if its col AA no longer holds the placeholder — auditor row shifts)
  - data/listing_photos/<safe_sku(placeholder)>.jpg -> <safe_sku(real)>.jpg
  - data/hosted_photos.json key safe_sku(placeholder) -> safe_sku(real) (the whole entry: url,
    sha256, uploaded_at, gallery) — the same safe_sku key photo_compositor / upload_photos /
    ebay_export share
Skipped (reported): no parseable Costco id in col R; the real id is already some other row's
col AA, or two placeholder rows map to the same id (a duplicate product — fix by hand); a photo or
hosted entry already exists under the real id (never overwritten).

Idempotent: a re-run finds no placeholders left. --dry-run reads the sheet + local files only.

Spec: docs/superpowers/specs/2026-10-21-fix-placeholder-skus.md

Usage:
    python tools/fix_placeholder_skus.py --dry-run
    python tools/fix_placeholder_skus.py
"""
import argparse
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import yaml  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

_ROOT = Path(__file__).resolve().parent.parent
load_dotenv(_ROOT / ".env", encoding="utf-8", override=True)

from tools import upload_photos as up  # noqa: E402
from tools.backfill_skus import extract_product_id  # noqa: E402
from tools.photo_compositor import OUTPUT_DIR, safe_sku  # noqa: E402

WRITE_DELAY = 1.1   # Sheets caps writes at 60/min per service account


def _col(letters):
    n = 0
    for ch in letters.upper():
        n = n * 26 + (ord(ch) - 64)
    return n - 1


def _cell(row, i):
    return str(row[i]).strip() if i < len(row) else ""


def is_placeholder(sku) -> bool:
    s = str(sku or "").strip()
    return bool(s) and not s.isdigit()


def plan_fixes(rows, start, COL):
    """-> (fixes, skipped). fixes = [{row, title, old, new}]; skipped = [(row, title, old, why)]."""
    aa, r_i, t_i = _col(COL["sku"]), _col(COL["costco_url"]), _col(COL["title"])
    real_in_use = {}
    for off, r in enumerate(rows):
        v = _cell(r, aa)
        if v and v.isdigit():
            real_in_use.setdefault(v, start + off)

    candidates, skipped = [], []
    for off, r in enumerate(rows):
        if not r:
            continue
        old = _cell(r, aa)
        if not is_placeholder(old):
            continue
        row, title = start + off, _cell(r, t_i)
        new = extract_product_id(_cell(r, r_i))
        if not new:
            skipped.append((row, title, old, "no parseable Costco id in col R"))
        elif new in real_in_use:
            skipped.append((row, title, old, f"{new} is already col AA of row {real_in_use[new]}"))
        else:
            candidates.append({"row": row, "title": title, "old": old, "new": new})

    by_new = {}
    for c in candidates:
        by_new.setdefault(c["new"], []).append(c)
    fixes = []
    for c in candidates:
        dupes = by_new[c["new"]]
        if len(dupes) > 1:
            skipped.append((c["row"], c["title"], c["old"],
                            f"{c['new']} maps from {len(dupes)} rows {[d['row'] for d in dupes]}"))
        else:
            fixes.append(c)
    return fixes, sorted(skipped)


def plan_photo_moves(fix, photos_dir, hosted):
    """-> (moves, conflicts) for one fix. moves: [("jpg"|"hosted", old_key, new_key)]."""
    old_k, new_k = safe_sku(fix["old"]), safe_sku(fix["new"])
    moves, conflicts = [], []
    if (Path(photos_dir) / f"{old_k}.jpg").exists():
        if (Path(photos_dir) / f"{new_k}.jpg").exists():
            conflicts.append(f"{new_k}.jpg already exists — {old_k}.jpg not renamed")
        else:
            moves.append(("jpg", old_k, new_k))
    if old_k in hosted:
        if new_k in hosted:
            conflicts.append(f"hosted_photos.json already has {new_k} — {old_k} entry not moved")
        else:
            moves.append(("hosted", old_k, new_k))
    return moves, conflicts


def apply_photo_moves(moves, photos_dir, hosted):
    """Rename jpgs / move hosted entries in place (caller saves hosted)."""
    for kind, old_k, new_k in moves:
        if kind == "jpg":
            os.replace(Path(photos_dir) / f"{old_k}.jpg", Path(photos_dir) / f"{new_k}.jpg")
        else:
            hosted[new_k] = hosted.pop(old_k)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Placeholder col AA SKUs -> real Costco ids")
    ap.add_argument("--dry-run", action="store_true", help="print the map, change nothing")
    args = ap.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")

    with open(_ROOT / "config" / "col_map.yaml") as f:
        COL = yaml.safe_load(f)["columns"]
    with open(_ROOT / "config" / "categories.yaml") as f:
        business = yaml.safe_load(f)["business"]
    from tools.sheet_writer import get_sheets_service, read_sheet, safe_write_row
    service = get_sheets_service()
    sheet, start, end = business["sheet_name"], business["data_start_row"], business["data_end_row"]
    rng = f"'{sheet}'!A{start}:AA{end}"
    rows = read_sheet(service, rng)

    fixes, skipped = plan_fixes(rows, start, COL)
    hosted = up.load_hosted()
    prefix = "[DRY RUN] " if args.dry_run else ""
    print(f"{prefix}{len(fixes)} placeholder SKU(s) to fix · {len(skipped)} skipped")

    fresh = None if args.dry_run else read_sheet(service, rng)   # re-check right before writing
    aa = _col(COL["sku"])
    n_fixed, n_jpg, n_hosted, conflicts_all, failed = 0, 0, 0, [], []
    for fix in fixes:
        moves, conflicts = plan_photo_moves(fix, OUTPUT_DIR, hosted)
        photo_txt = ", ".join(f"{k} {o}→{n}" for k, o, n in moves) or "no photo"
        print(f"  row {fix['row']} · {fix['old']} → {fix['new']} · {fix['title'][:50]} · {photo_txt}")
        for c in conflicts:
            print(f"      ⚠️ {c}")
            conflicts_all.append((fix, c))
        if args.dry_run:
            n_jpg += sum(k == "jpg" for k, _, _ in moves)
            n_hosted += sum(k == "hosted" for k, _, _ in moves)
            continue
        off = fix["row"] - start
        if off >= len(fresh) or _cell(fresh[off], aa) != fix["old"]:
            failed.append((fix, "row changed since the read (col AA no longer the placeholder)"))
            print("      ✗ row changed — not written")
            continue
        try:
            safe_write_row(service, sheet, fix["row"], [(COL["sku"], fix["new"])])
        except Exception as e:
            failed.append((fix, f"sheet write failed: {e}"))
            print(f"      ✗ sheet write failed: {e}")
            continue
        n_fixed += 1
        apply_photo_moves(moves, OUTPUT_DIR, hosted)
        if any(k == "hosted" for k, _, _ in moves):
            up.save_hosted(hosted)
        n_jpg += sum(k == "jpg" for k, _, _ in moves)
        n_hosted += sum(k == "hosted" for k, _, _ in moves)
        time.sleep(WRITE_DELAY)

    for row, title, old, why in skipped:
        print(f"  SKIPPED row {row} · {old} · {title[:50]}: {why}")
    for fix, why in failed:
        print(f"  FAILED  row {fix['row']} · {fix['old']}: {why}")
    verb = "would fix" if args.dry_run else "fixed"
    print(f"\n{prefix}Summary: {verb} {len(fixes) if args.dry_run else n_fixed} SKU(s) · "
          f"photos renamed {n_jpg} · hosted entries moved {n_hosted} · conflicts {len(conflicts_all)} · "
          f"skipped {len(skipped)} · failed {len(failed)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
